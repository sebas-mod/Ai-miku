import { stopAllJadibots, getActiveJadibots } from '../../src/lib/features/jadibot-manager.js'
import te from '../../src/lib/core/error.js'
const pluginConfig = {
    name: 'stopalljadibot',
    alias: ['stopsemuajadibot', 'killalljadibots'],
    category: 'owner',
    description: 'Hentikan semua jadibot yang aktif',
    usage: '.stopalljadibot',
    example: '.stopalljadibot',
    isOwner: true,
    isPremium: false,
    isGroup: false,
    isPrivate: false,
    cooldown: 10,
    energi: 0,
    isEnabled: true
}

async function handler(m, { sock }) {
    const active = getActiveJadibots()

    if (active.length === 0) {
        return m.reply(`❌ No hay ningún jadibot activo`)
    }

    await m.react('🕕')

    try {
        const stopped = await stopAllJadibots()

        await m.react('✅')

        const names = stopped.map(id => `@${id}`).join(', ')

        await sock.sendMessage(m.chat, {
            text: `🛑 *TODOS LOS JADIBOTS DETENIDOS*\n\n` +
                `> 📊 Total: *${stopped.length}* jadibot\n` +
                `> 💾 Sesión: *guardada*\n\n` +
                `Dihentikan: ${names}\n\n` +
                `> Todas las sesiones se guardaron y pueden reactivarse.`,
            mentions: stopped.map(id => id + '@s.whatsapp.net')
        }, { quoted: m })
    } catch (error) {
        await m.react('☢')
        await m.reply(te(m.prefix, m.command, m.pushName))
    }
}

export { pluginConfig as config, handler }
